package com.ccit.area.sales.common.swdp3.widgets;

public class Page extends Panel {
	
	private String mboname = null;
	private String beanclass = null;
	private String version = null;
	private String fileName = null;

	public String getFileName() {
		return fileName;
	}

	public void setFileName(String fileName) {
		this.fileName = fileName;
	}

	public String getMboname() {
		return mboname;
	}

	public void setMboname(String mboname) {
		this.mboname = mboname;
	}

	public String getBeanclass() {
		return beanclass;
	}

	public void setBeanclass(String beanclass) {
		this.beanclass = beanclass;
	}

	public String getVersion() {
		return version;
	}

	public void setVersion(String version) {
		this.version = version;
	}

}
